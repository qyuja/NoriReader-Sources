#!/usr/bin/env python3
"""Generate standalone sources with declarations first and execution methods below."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
MODULES = ROOT / 'src'
OUTPUT = ROOT
DEFINITION_ENTRY = 'var source = createSource(sourceDefinitions.websites);'

definitions = (MODULES / 'source-definitions.js').read_text()
methods = '\n'.join(
    (MODULES / name).read_text().removeprefix('"use strict";\n').lstrip()
    for name in ['websites.js', 'catalogs.js', 'novel-reading.js', 'drives.js']
)
header = '// Generated by scripts/build_source.py. Edit the declarations and adapter modules.\n'
for profile, filename in [('official', 'index.js'), ('novels', 'novels.js')]:
    code = header + definitions.replace(
        DEFINITION_ENTRY, f'var source = createSource(sourceDefinitions.{profile});'
    ) + '\n// 执行区：读取上方定义，执行请求与解析；不追加或修改站点注册信息。\n\n' + methods
    (OUTPUT / filename).write_text(code)

# A drive-only package contains no website declarations or scraping adapters.
drive_rules_text = definitions.split('const driveRules = ', 1)[1].split('\n};', 1)[0] + '\n}'
drive_rules = json.loads(drive_rules_text)
profiles_text = definitions.split('const sourceDefinitions = ', 1)[1]
drive_profile = json.JSONDecoder().raw_decode(profiles_text.split('"drives": ', 1)[1])[0]
drive_declarations = ('const driveRules = ' + json.dumps(drive_rules, ensure_ascii=False, indent=2) + ';\n\n'
    + 'const definition = ' + json.dumps(drive_profile, ensure_ascii=False, indent=2) + ';\n\n')
drive_entry = '''var source = {
  manifest: {
    apiVersion: definition.apiVersion, id: definition.id, name: definition.name, version: definition.version,
    domains: Array.from(new Set(definition.driveIDs.flatMap(id => driveRules[id].authentication.domains))),
    sites: [], settings: [],
    drives: definition.driveIDs.map(id => {
      const {name, root, authentication} = driveRules[id];
      return {id, name, root, authentication};
    })
  },
  driveList(input) {return driveList(input);},
  driveResolve(input) {return driveResolve(input);},
  driveShareList(input) {return driveShareList(input);},
  driveTransfer(input) {return driveTransfer(input);},
  driveTransferStatus(input) {return driveTransferStatus(input);}
};
'''
(OUTPUT / 'cloud-drives.js').write_text(header + drive_declarations + drive_entry + '\n'
    + (MODULES / 'drives.js').read_text().removeprefix('"use strict";\n').lstrip())

print(OUTPUT / 'index.js')
print(OUTPUT / 'novels.js')
print(OUTPUT / 'cloud-drives.js')
